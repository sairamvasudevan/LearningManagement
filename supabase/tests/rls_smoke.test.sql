begin;
select plan(20);
select has_table('public','profiles','profiles table exists');
select has_table('public','user_roles','user roles table exists');
select has_table('public','course_enrollments','course enrollments table exists');
select has_table('public','lesson_progress','lesson progress table exists');
select has_table('public','assessment_questions','assessment question table exists');
select has_table('public','assessment_attempts','assessment attempt table exists');
select has_table('private','assessment_answer_keys','answer keys are stored in the private schema');
select ok((select relrowsecurity from pg_class where oid='public.profiles'::regclass),'RLS enabled on profiles');
select ok((select relrowsecurity from pg_class where oid='public.course_enrollments'::regclass),'RLS enabled on enrollments');
select ok((select relrowsecurity from pg_class where oid='public.assessment_responses'::regclass),'RLS enabled on assessment responses');
select ok(not has_table_privilege('anon','public.profiles','SELECT'),'anonymous users cannot read student profiles');
select ok(not has_table_privilege('authenticated','private.assessment_answer_keys','SELECT'),'students cannot read private answer keys');
select ok(not has_table_privilege('authenticated','public.user_roles','INSERT'),'students cannot grant themselves roles');
select ok(not has_table_privilege('authenticated','public.course_enrollments','UPDATE'),'students cannot change their own enrolment status');
select ok(not has_table_privilege('authenticated','public.assessment_responses','INSERT'),'students cannot directly insert assessment results');
select ok(not has_table_privilege('authenticated','public.assessment_attempts','INSERT'),'students cannot directly create assessment attempts');
select ok(not has_table_privilege('authenticated','public.lesson_progress','INSERT'),'students cannot directly mark lessons complete');
select ok(not has_table_privilege('authenticated','public.course_invites','INSERT'),'students cannot create invitations');
select ok(has_function_privilege('authenticated','public.submit_assessment_answer(uuid,text,smallint)','EXECUTE'),'authenticated students submit through the scoring RPC');
select ok(not has_function_privilege('anon','public.submit_assessment_answer(uuid,text,smallint)','EXECUTE'),'anonymous users cannot call the scoring RPC');
select * from finish();
rollback;
